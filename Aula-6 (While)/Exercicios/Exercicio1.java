package Exercicios;

class Exercicio1 {
    //Sequencia_de_While

    public static void main(String[] args) {

        // Inicializa a variável de controlo com o valor inicial (100)
        int numero = 100;

        // O laço executa enquanto o valor de 'numero' for menor ou igual a 200
        while (numero <= 200) {

            // Imprime o valor atual da variável
            System.out.println(numero);

            // Incrementa o valor em 1 a cada repetição
            numero++;
        }
    }
}
