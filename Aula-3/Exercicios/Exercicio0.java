package Exercicios;

public class Exercicio0 {
    public static void main(String[] args) {
        
        // 1. Texto simples: Imprime a mensagem padrão de boas-vindas na programação
        System.out.println("Hello World!!");
        
        // 2. Concatenação de Texto + Número: O Java converte o número 18 em texto e o une com a frase
        System.out.println("Minha idade é " + 18 + " anos");
        
        // 3. Expressão Lógica (Booleana):
        // Primeiro calcula a soma: (3 + 5 = 8)
        // Depois compara com o operador menor ou igual: (8 <= 22)
        // Como 8 é menor ou igual a 22, o resultado retornado é 'true' (verdadeiro)
        System.out.println("resultado é: " + (3 + 5 <= 22));
    }
}