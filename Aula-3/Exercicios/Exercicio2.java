package Exercicios;

public class Exercicio2 {
    public static void main(String[] args) {
        
        // Declaração das variáveis com seus respectivos tipos de dados
        int idade = 22;                  // Tipo inteiro (int) para a idade
        double altura = 1.65;            // Tipo decimal (double) para a altura (em metros)
        String statusAula = "Presente";  // Tipo texto (String) para o status ("Presente" ou "Ausente")

        // Impressão dos valores, cada um em uma linha
        System.out.println("Idade: " + idade + " anos");
        System.out.println("Altura: " + altura + " m");
        System.out.println("Status na aula: " + statusAula);
    }
}